// Validates the curriculum JSON files. With an output path it also writes an
// equivalent SQL seed (useful for a fresh database without the app).
// Usage: node supabase/curriculum/build-seed.mjs --check | <output.sql>
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const SUBJECTS = ['mathematics', 'english', 'science', 'geography']
const BANDS = ['3-4', '5-6', '7-9', '10-12', '13+']
const MIN_PER_BAND = 30

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const errors = []
const keys = new Set()
const rows = []
const subjectRows = []

for (const slug of SUBJECTS) {
  const data = JSON.parse(readFileSync(join(here, `${slug}.json`), 'utf8'))
  if (data.subject !== slug) errors.push(`${slug}: subject field is ${data.subject}`)
  subjectRows.push(`(${q(slug)}, ${q(data.name)}, ${SUBJECTS.indexOf(slug) + 1})`)
  for (const band of BANDS) {
    const list = data.bands?.[band]
    if (!Array.isArray(list)) { errors.push(`${slug} ${band}: missing`); continue }
    if (list.length < MIN_PER_BAND) errors.push(`${slug} ${band}: ${list.length} concepts (< ${MIN_PER_BAND})`)
    list.forEach((c, i) => {
      if (!Array.isArray(c) || c.length !== 5 || c.some(v => typeof v !== 'string' || !v.trim())) {
        errors.push(`${slug} ${band} #${i + 1}: bad shape`); return
      }
      const [key, name, objective, nc, strand] = c
      if (!/^[a-z0-9_]+$/.test(key)) errors.push(`${key}: invalid key`)
      if (keys.has(key)) errors.push(`${key}: duplicate key`)
      keys.add(key)
      if (objective.length < 25) errors.push(`${key}: objective too short`)
      rows.push(`(${q(key)}, ${q(name)}, ${q(objective)}, ${q(nc)}, ${q(strand)}, ${i + 1}, ${q(slug)}, ${q(band)})`)
    })
  }
}

if (errors.length) {
  console.error(errors.join('\n'))
  process.exit(1)
}

const sql = `-- GENERATED by supabase/curriculum/build-seed.mjs — do not edit by hand.
-- ${rows.length} concepts across ${SUBJECTS.length} subjects and ${BANDS.length} age bands.
begin;

insert into public.subjects (slug, name, sort) values
${subjectRows.join(',\n')}
on conflict (slug) do update set name = excluded.name, sort = excluded.sort;

delete from public.subjects where slug not in (${SUBJECTS.map(q).join(', ')});

with src (concept_key, concept_name, concept_description, nc_reference, strand, sequence_order, subject_slug, band) as (
  values
${rows.join(',\n')}
)
insert into public.curriculum_concepts
  (concept_key, concept_name, concept_description, nc_reference, strand, sequence_order, subject_id, age_group_id)
select s.concept_key, s.concept_name, s.concept_description, s.nc_reference, s.strand, s.sequence_order, sub.id, ag.id
from src s
join public.subjects sub on sub.slug = s.subject_slug
join public.age_groups ag on ag.label = s.band
on conflict (concept_key) do update set
  concept_name = excluded.concept_name,
  concept_description = excluded.concept_description,
  nc_reference = excluded.nc_reference,
  strand = excluded.strand,
  sequence_order = excluded.sequence_order,
  subject_id = excluded.subject_id,
  age_group_id = excluded.age_group_id;

-- Remove concepts that are no longer in the source files.
delete from public.curriculum_concepts
where concept_key not in (select concept_key from (values ${[...keys].map(k => `(${q(k)})`).join(', ')}) v(concept_key));

commit;
`

if (!process.argv[2] || process.argv[2] === '--check') {
  console.log(`OK: ${rows.length} concepts valid`)
  process.exit(0)
}
const out = process.argv[2]
writeFileSync(out, sql)
console.log(`OK: ${rows.length} concepts → ${out}`)
